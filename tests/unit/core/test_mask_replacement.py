"""Behavior-preserving extraction proof for ``apply_mask_replacement``.

The legacy replacement block of ``despike_r1_spectrum``
was extracted into ``apply_mask_replacement``; this battery proves the
extraction is behavior-preserving against vectors **pinned from the
pre-extraction legacy arithmetic** (computed at commit ccb4d27's
generation: ``s.loc[mask] = nan; s.interpolate(method, limit_direction=
"both")``) plus an inline legacy-arithmetic equivalence sweep.

Also pins one full ``despike_r1_spectrum`` end-to-end output digest from
the pre-extraction code, so the loop refactor itself is covered, not just
the helper.
"""

import hashlib

import numpy as np
import pandas as pd
import pytest

from sherloc_pipeline.core.preprocessing import (
    DespikeParams,
    apply_mask_replacement,
    despike_r1_spectrum,
)


def _legacy_replace(series: pd.Series, mask: pd.Series, method: str) -> pd.Series:
    """The pre-extraction replacement arithmetic, verbatim."""
    s = series.astype(float).copy()
    s.loc[mask] = np.nan
    return s.interpolate(method=method, limit_direction="both")


